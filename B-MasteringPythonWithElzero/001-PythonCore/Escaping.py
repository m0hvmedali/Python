# escaping letters in python
# \n -> new line line feed
# \b -> backspace 
# \newline -> new line
# \t -> tab
# \r -> carriage return
print("1234\r5678")
# Escape Back Slash
print("I Love Back Slash\\")
# Escape Single Quote
print('I Love Single Quote\'s') 
print ("i love single qouts ''")
print("mohamed\naly")
print("mohamed\baly")
print("mohmed\taly")

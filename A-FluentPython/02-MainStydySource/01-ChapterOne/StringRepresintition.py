# ### 1️⃣ أولاً: دالة الـ `__repr__` (البطاقة الشخصية الرسمية للمطور)

# #### 👶 الشرح المبسط (من 0% لـ 100%):
# لما بتفتح كونسول بايثون التفاعلي وتكتب اسم الكائن وتضغط `Enter` مباشرة، بايثون بتنادي دالة اسمها `__repr__` (اختصار لـ Representation) [cite: 214, 215]. 

# لو إنت ما كتبتلوش دالة `__repr__` مخصصة بإيدك، بايثون هترتبك وتطلعلك شكل غريب ومبهم ملوش أي معنى للطفل أو للمطور، زي ده [cite: 214]:
# `<Vector object at 0x10e100070>`

# عشان كده، الكاتب بيقولنا إن **القاعدة الذهبية** لـ `__repr__` هي:
# **"لازم النص اللي يرجع منها يكون واضح جداً وبدون أي غموض، ويا سلام لو كان شبه كود البرمجة اللي بنستعمله لإنشاء الكائن ده بالظبط!"** [cite: 216].

# يعني مثلاً، لما نطبع كائن المتجه (Vector)، المفروض يظهر للمطور كده: `Vector(3, 4)` [cite: 216]. ده كود واضح ومفهوم ومفيش فيه أي لغس [cite: 216]!

# #### 🌐 الربط مع موقع بايثون الرسمي (Python Docs):
# في دليل بايثون التمهيدي (**An Informal Introduction to Python**)، بيشرح لنا إن كونسول بايثون (الـ Shell) بيعرض الحاجات بشكلها الخام (الرسمي) [cite: 166]. 

# على سبيل المثال، لو كتبت نصاً يحتوي على سطر جديد (`\n`) وضغطت `Enter` مباشرة في الـ Shell بدون `print` [cite: 166]:
# ```python
# >>> s = 'First line.\nSecond line.'
# >>> s
# 'First line.\nSecond line.'
# ```
# هنا بايثون عرضت النص بـ **علامات الاقتباس وحرف الـ `\n` الظاهر** [cite: 166]! ليه؟ عشان دي طريقة الـ `repr()` اللي بتوريك الحقيقة المجرّدة بدون تجميل عشان كمطور تفهم الكائن جواه إيه بالظبط [cite: 166, 214].


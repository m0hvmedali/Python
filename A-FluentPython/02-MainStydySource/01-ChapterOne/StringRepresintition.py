# ### 4️⃣ رابعاً: خطة الإنقاذ البديلة (The Fallback Rule)

# #### 👶 الشرح المبسط (من 0% لـ 100%):
# بايثون ذكية جداً وبتحب تريحنا. لو إنت تعبت وعملت دالة الـ `__repr__` الرسمية ومكسل تكتب دالة الـ `__str__` اللطيفة [cite: 216, 217]:
# * بايثون مش هتقول لأ! لما المبرمج يكتب `print(my_object)`، بايثون هتروح تدور على `__str__` [cite: 216].
# * لو ملقتهاش، هتقول: **"خلاص مش مشكلة، أنا هستعمل الـ `__repr__` كبديل احتياطي (Fallback)"** وتطبعها هي [cite: 216, 217].

# **لكن العكس غير صحيح!** 
# لو عملت `__str__` بس ونسيت تعمل `__repr__` [cite: 217]، وجيت تعرض الكائن في الكونسول التفاعلي، بايثون مش هتستخدم `__str__` البديلة، وهترجع تظهرلك السطر المقيد البايخ: `<Vector object at 0x...>` [cite: 214].

# #### 💡 النصيحة الذهبية من الكاتب (ص. 12):
# > "إذا قررت تطبق دالة واحدة بس من الاتنين في الكود بتاعك... اختار دايماً **`__repr__`**" [cite: 217]. لأنها بتضرب عصفورين بحجر؛ بتفيد المطور في الفحص والتصحيح، وبتشتغل كبديل تلقائي للمستخدم عند الطباعة [cite: 214, 216, 217].


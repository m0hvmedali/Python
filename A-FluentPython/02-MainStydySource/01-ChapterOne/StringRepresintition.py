# ### 3️⃣ ثالثاً: دالة الـ `__str__` (الوجه اللطيف والجميل للمستخدم)

# #### 👶 الشرح المبسط (من 0% لـ 100%):
# دالة الـ `__str__` بنستدعيها لما نحب نعرض الكائن بشكل منسق ولطيف جداً ومريح للعين [cite: 216]. الدالة دي هي اللي بايثون بتناديها تلقائياً لما تكتب أمر الطباعة الشهير: **`print(my_object)`** [cite: 216].

# هدفها الأساسي: **عرض نص جميل ومفهوم لعموم الناس (المستخدم النهائي) اللي ميفهموش في البرمجة والكود** [cite: 216].

# * **مثال توضيحي:** 
#   * الـ `__repr__` للكارت هيظهر للمطور كده: `Card(rank='A', suit='spades')` [cite: 18].
#   * لكن الـ `__str__` اللطيف اللي ممكن تعرضه للمستخدم في اللعبة هو: `Ace of Spades ♠️`!

# #### 🌐 الربط مع موقع بايثون الرسمي (Python Docs):
# في وثائق بايثون التمهيدية، بيكتبوا قاعدة صريحة وجميلة جداً [cite: 166]:
# > "The `print()` function produces a more readable output, by omitting the enclosing quotes and by printing escaped and special characters" [cite: 166].

# وده معناه إن وظيفة دالة `print()` (واللي بتعتمد كلياً على `__str__` و `str()`) هي إنها **تخفي علامات الاقتباس وتنفذ السطور الجديدة** عشان تطلع شكل النص مريح ومنسق للقراءة البشرية [cite: 166, 216]. 

# زي المثال اللي فات [cite: 166]:
# ```python
# >>> print(s)
# First line.
# Second line.
# ```
# شايف الجمال؟ السطر الجديد اتقسم فعلاً وعلامات الاقتباس اختفت تماماً [cite: 166]!


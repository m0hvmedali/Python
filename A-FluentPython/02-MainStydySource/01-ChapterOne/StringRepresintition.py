# ### 2️⃣ ثانياً: سحر الـ `!r` داخل الـ `f-strings` (ص. 11)

# #### 👶 الشرح المبسط (من 0% لـ 100%):
# في كود الكاتب، لما جه يعمل دالة الـ `__repr__` كتب السطر ده [cite: 209]:
# ```python
# return f'Vector({self.x!r}, {self.y!r})'
# ```
# **ليه حط علامة التعجب وحرف الـ `r` (`!r`)؟** 

# تخيل إن عندنا كارتين لعب:
# * الكارت الأول جواه **رقم** `1`.
# * الكارت الثاني جواه **نص (كلمة)** `'1'`.

# لو طبعناهم عادي من غير الـ `!r`، الاتنين هيظهروا على الشاشة كأنهم `1` مش هتعرف تفرق مين الرقم ومين النص!
# لكن لما بنكتب `!r` (واللي معناها يا بايثون استدعي دالة الـ `repr` على المتغير ده) [cite: 215]:
# * الرقم `1` هيتكتب: `1`.
# * النص `'1'` هيتكتب جوه علامات اقتباس: `'1'` [cite: 215].

# الحركة الذكية دي بتخلي المطور يعرف فوراً لو حصلت لخبطة وتم تمرير نصوص بدل أرقام للكائن (زي تمرير `'1'` بدلاً من `1`) [cite: 215].

# #### 🌐 الربط مع موقع بايثون الرسمي (Python Docs):
# في قسم السلاسل النصية وتنسيقها (**Format string syntax**)، بتوضح وثائق بايثون الرسمية إن الـ `f-strings` بتدعم حقول التحويل (Conversion Fields) زي `!r` لاستدعاء دالة `repr()` تلقائياً، والـ `!s` لاستدعاء دالة `str()` [cite: 170, 215].

